import { readFile, readdir, rm, mkdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import react from '@vitejs/plugin-react';
import { build } from 'vite';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputDirectory = join(root, '.report-build');
const generatedPath = join(root, 'src', 'generated', 'report-app.ts');

await rm(outputDirectory, { recursive: true, force: true });
await build({
  root,
  configFile: false,
  logLevel: 'warn',
  define: { 'process.env.NODE_ENV': JSON.stringify('production') },
  plugins: [react()],
  build: {
    assetsInlineLimit: Number.MAX_SAFE_INTEGER,
    cssCodeSplit: false,
    emptyOutDir: true,
    minify: 'esbuild',
    outDir: outputDirectory,
    sourcemap: false,
    lib: {
      entry: join(root, 'src', 'report-app', 'main.tsx'),
      formats: ['iife'],
      name: 'FelanInsightsReport',
      fileName: () => 'report.js',
    },
  },
});

const outputFiles = await readdir(outputDirectory);
const scriptPath = join(outputDirectory, 'report.js');
const styleName = outputFiles.find((name) => name.endsWith('.css'));
if (!styleName) throw new Error('The Insights report build did not emit CSS');

const [script, style, favicon] = await Promise.all([
  readFile(scriptPath, 'utf8'),
  readFile(join(outputDirectory, styleName), 'utf8'),
  readFile(join(root, 'assets', 'felan-icon.svg')),
]);
const moduleSource = [
  '// Generated by scripts/build-report-app.mjs. Do not edit.',
  `export const REPORT_APP_SCRIPT = ${JSON.stringify(script)};`,
  `export const REPORT_APP_STYLE = ${JSON.stringify(style)};`,
  `export const REPORT_FAVICON = ${JSON.stringify(`data:image/svg+xml;base64,${favicon.toString('base64')}`)};`,
  '',
].join('\n');

await mkdir(dirname(generatedPath), { recursive: true });
await writeFile(generatedPath, moduleSource);
await rm(outputDirectory, { recursive: true, force: true });
